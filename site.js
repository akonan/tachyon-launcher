/* Tachyon site: motion and charts. Rule of motion: the world eases, Tachyon cuts.
   Every chart value comes from data.js (generated by build-data.py). */
(function () {
  const D = window.TACHYON || {}, S = window.SCREENS || {};
  const $ = (s, r) => (r || document).querySelector(s), $$ = (s, r) => [...(r || document).querySelectorAll(s)];
  const clamp = (x, a = 0, b = 1) => Math.min(b, Math.max(a, x));
  const ease = t => 1 - Math.pow(1 - t, 3);
  const fmt = v => (v >= 100 ? +v.toFixed(1) : Math.round(v * 10 - 1e-6) / 10).toString();   /* below 100, halves round down, as the summaries print them */
  const still = matchMedia('(prefers-reduced-motion: reduce)').matches || /[?&]still/.test(location.search);
  if (still) document.documentElement.classList.add('still');
  const row = (f, id) => f.rows.find(r => r.id === id);
  const el = (tag, cls, html) => { const e = document.createElement(tag); if (cls) e.className = cls; if (html != null) e.innerHTML = html; return e; };

  /* theme */
  const inv = $('#invert');
  const setInv = on => { document.documentElement.classList.toggle('inv', on); if (inv) inv.setAttribute('aria-pressed', on); try { localStorage.setItem('tachyon-inv', on ? 1 : 0); } catch (e) {} };
  try { if (localStorage.getItem('tachyon-inv') === '1') setInv(true); } catch (e) {}
  if (inv) inv.onclick = () => setInv(!document.documentElement.classList.contains('inv'));

  if (window.mountScreens) mountScreens();

  /* generic bar charts (fine print, blog) */
  $$('[data-chart]').forEach(c => {
    const f = D[c.dataset.chart]; if (!f) return;
    const div = +c.dataset.div || 1, unit = c.dataset.unit || '';
    const max = +c.dataset.max || Math.max(...f.rows.filter(r => r.ok).map(r => r.median / div)) * 1.12;
    f.rows.forEach(r => {
      const me = r.id === (c.dataset.me || 'palma'), v = r.median / div;
      const b = el('div', 'brow' + (me ? ' me' : '') + (r.ok ? '' : ' na'));
      const w = r.ok ? clamp(v / max) * 100 : 0;
      b.innerHTML = `<span class="nm">${r.name}</span><span class="t"><span class="b" style="width:${w}%"></span><span class="v" style="left:${w}%">${r.ok ? fmt(v) + ' ' + unit : (r.median ? 'not reportable, ' : 'no valid run, ') + r.n + ' of ' + r.attempts + ' valid'}</span></span>`;
      c.appendChild(b);
    });
  });

  /* ---------- hero: a real-time cold start ---------- */
  const hero = $('#heroPhone');
  if (hero && D.coldClean) {
    const ms = row(D.coldClean, 'palma').median, out = $('#heroMs'), note = $('#heroNote');
    hero.innerHTML = S.blank() + '<div class="layer" hidden>' + S.home() + '</div>';
    const home = hero.lastChild;
    const run = slow => {
      home.hidden = true; note.textContent = slow > 1 ? `cold start, ${slow}× slower` : 'cold start, replayed at real speed';
      const t0 = performance.now();
      const tick = now => {
        const t = (now - t0) / slow;
        if (t >= ms) { out.textContent = fmt(ms); home.hidden = false; return; }
        out.textContent = Math.floor(t); requestAnimationFrame(tick);
      };
      requestAnimationFrame(tick);
    };
    if (still) { out.textContent = fmt(ms); home.hidden = false; } else (document.fonts ? document.fonts.ready : Promise.resolve()).then(() => setTimeout(() => run(1), 350));
    $$('[data-replay]').forEach(b => b.onclick = () => run(+b.dataset.replay));
  }

  /* ---------- stages ---------- */
  const stages = {};

  stages.question = (p, root) => {
    const words = $$('.line span', root), n = words.length;
    words.forEach((w, i) => w.classList.toggle('on', p >= (i + .4) / (n + 3.2)));
    const flip = p > .6;
    root.classList.toggle('inv-sec', flip); $('.ans', root).hidden = !flip;
  };

  /* race: scroll is time */
  (function () {
    const lanes = $('#raceLanes'); if (!lanes || !D.coldField) return;
    const MAX = 900, f = D.coldField, ruler = $('#raceRuler');
    for (let t = 0; t <= MAX; t += 150) ruler.appendChild(el('i', '', t)).style.left = (t / MAX * 100) + '%';
    const hand = ruler.appendChild(el('span', 'hand'));
    const rows = f.rows.map(r => {
      const me = r.id === 'palma';
      const l = el('div', 'lane' + (me ? ' me' : '') + (r.ok ? '' : ' na'));
      l.innerHTML = `<span class="nm">${r.name}</span><span class="trk">${r.ok ? `<span class="bar"></span><span class="ci" style="left:${r.lo / MAX * 100}%;width:${(r.hi - r.lo) / MAX * 100}%"></span>` : (r.median ? `not reportable: ${r.n} of ${r.attempts} valid` : `no valid cold start: ${r.n} of ${r.attempts}`)}</span><span class="val">${r.ok ? fmt(r.median) + ' ms' : ''}</span>`;
      lanes.appendChild(l);
      return { r, l, bar: $('.bar', l) };
    });
    const T = $('#raceT'), V = $('#raceV');
    stages.race = p => {
      const t = clamp(p * 1.12) * MAX * 1.02;
      T.textContent = Math.min(MAX, Math.round(t)); hand.style.left = clamp(t / MAX) * 100 + '%';
      rows.forEach(({ r, l, bar }) => {
        if (!r.ok) return;
        const done = t >= r.median;
        l.classList.toggle('done', done);
        bar.style.width = Math.min(t, r.median) / MAX * 100 + '%';
      });
      V.hidden = t < MAX;
    };
  })();

  /* duel: three phones, clean host */
  (function () {
    const box = $('#duelDevs'); if (!box || !D.coldClean) return;
    const f = D.coldClean, MAX = 290;
    const items = f.rows.map(r => {
      const me = r.id === 'palma', fig = el('figure');
      fig.innerHTML = `<div class="device"><div class="phone">${S.blank()}<div class="layer ${me ? '' : 'rv'}" ${me ? 'hidden' : ''}>${me ? S.home() : S.rival()}</div></div></div><figcaption>${r.name}<span class="num">0 ms</span></figcaption>`;
      box.appendChild(fig);
      return { r, me, layer: $('.layer', fig), num: $('.num', fig) };
    });
    const T = $('#duelT'), V = $('#duelV');
    stages.duel = p => {
      const t = clamp(p * 1.15) * MAX;
      T.textContent = Math.round(t);
      items.forEach(({ r, me, layer, num }) => {
        const done = t >= r.median;
        num.textContent = fmt(Math.min(t, r.median)) + ' ms';
        if (me) layer.hidden = !done;
        else layer.style.opacity = clamp((t - (r.median - 22)) / 22);   /* rivals fade in, Tachyon cuts */
      });
      V.hidden = t < MAX - 1;
    };
  })();

  /* keyboard */
  (function () {
    const box = $('#kbdDevs'); if (!box || !D.kbdOn) return;
    const MAX = 340, ids = ['palma', 'kiss'];
    let on = true, lastP = 0;
    const scr = () => S.search({ q: '', rows: [], best: null, count: 'Search' }).replace('<b class="s-q"></b>', '<span class="s-ph">Search</span>');
    const items = ids.map(id => {
      const fig = el('figure');
      fig.innerHTML = `<div class="device"><div class="phone">${scr()}<span class="s-finger" hidden></span></div></div><figcaption>${id === 'palma' ? 'Tachyon' : 'KISS'}<span class="num">0 ms</span></figcaption>`;
      box.appendChild(fig);
      const k = $('.s-kbd', fig); k.style.willChange = 'transform';
      return { id, k, num: $('.num', fig), finger: $('.s-finger', fig) };
    });
    const T = $('#kbdT'), V = $('#kbdV'), btn = $('#kbdToggle');
    const draw = p => {
      lastP = p;
      const f = on ? D.kbdOn : D.kbdOff, t = clamp(p * 1.15) * MAX;
      T.textContent = Math.round(t);
      items.forEach(({ id, k, num, finger }) => {
        const m = row(f, id).median, done = t >= m;
        finger.hidden = !(t > 0 && t < m + 40);
        num.textContent = fmt(Math.min(t, m)) + ' ms';
        if (id === 'palma' || !on) k.style.transform = done ? 'none' : 'translateY(101%)';      /* cut */
        else { const x = clamp(t / m); k.style.transform = `translateY(${(1 - x * x * (3 - 2 * x)) * 101}%)`; }              /* slide */
      });
      const a = row(f, 'palma').median, b = row(f, 'kiss').median;
      V.innerHTML = on ? `${(b / a).toFixed(1)}× faster than KISS, the best rival.<sup><a href="#fn4">4</a></sup>` : `Animations off: ${fmt(a)} ms against ${fmt(b)} ms. A tie.<sup><a href="#fn4">4</a></sup>`;
      V.hidden = t < Math.max(a, b);
    };
    btn.onclick = () => { on = !on; btn.setAttribute('aria-pressed', on); btn.textContent = 'System animations: ' + (on ? 'on' : 'off'); draw(still ? 1 : lastP); };
    stages.kbd = draw;
  })();

  /* memory: one square per MB */
  (function () {
    const g = $('#memGrid'); if (!g || !D.memory) return;
    const blocks = D.memory.rows.map(r => {
      const mb = r.median / 1000, me = r.id === 'palma';
      const b = el('div', 'mb' + (me ? ' me on' : ''));
      b.innerHTML = `<div class="sq">${'<i></i>'.repeat(Math.round(mb))}</div><p class="nm">${r.name}</p><p class="mv">${mb.toFixed(1)} MB</p>`;
      g.appendChild(b); return b;
    });
    stages.mem = p => { const n = Math.floor(clamp(p * 1.25) * (blocks.length - 1) + .001); blocks.forEach((b, i) => b.classList.toggle('on', i <= n)); };
  })();

  /* film strip */
  (function () {
    const s = $('#strip'); if (!s) return;
    stages.film = p => { const over = Math.max(0, s.scrollWidth - innerWidth); s.style.transform = `translate3d(${-ease(clamp(p * 1.08)) * over}px,0,0)`; };
  })();

  const pins = $$('.pin[data-stage]').map(root => ({ root, fn: stages[root.dataset.stage] })).filter(x => x.fn);
  let queued = false;
  const frame = () => {
    queued = false;
    const vh = innerHeight;
    pins.forEach(({ root, fn }) => {
      const r = root.getBoundingClientRect();
      if (r.bottom < -vh || r.top > 2 * vh) return;
      fn(clamp(-r.top / Math.max(1, r.height - vh)), root);
    });
  };
  if (still) pins.forEach(({ root, fn }) => fn(1, root));
  else { addEventListener('scroll', () => { if (!queued) { queued = true; requestAnimationFrame(frame); } }, { passive: true }); addEventListener('resize', frame); frame(); }

  /* ---------- player: autoplay, next chapter ---------- */
  (function () {
    const box = $('#player'); if (!box || still) return;
    box.hidden = false;
    const play = $('#plPlay'), next = $('#plNext'), label = $('#plLabel'), bar = $('#plBar');
    const PIN = .45, FLOW = .3;                       /* viewport heights per second: stages, reading sections */
    const chs = () => $$('main > header, main > section, footer.foot').map(e => {
      const top = Math.round(e.getBoundingClientRect().top + scrollY);
      const st = $('.sticky', e);                    /* a stage ends when its sticky box lets go */
      return { top, end: top + Math.max(0, e.offsetHeight - (st ? st.offsetHeight : innerHeight)), pin: e.classList.contains('pin') };
    });
    const cur = c => { let i = 0; c.forEach((x, k) => { if (x.top <= scrollY + 4) i = k; }); return i; };
    let anim = null, playing = false;
    const show = () => {
      const c = chs();
      label.textContent = `${cur(c) + 1} / ${c.length}`;
      bar.style.setProperty('--p', clamp(scrollY / Math.max(1, document.documentElement.scrollHeight - innerHeight)));
      play.textContent = playing ? 'Pause' : 'Play'; play.setAttribute('aria-pressed', playing);
    };
    const stop = () => { if (anim) cancelAnimationFrame(anim.id); anim = null; playing = false; show(); };
    const tween = (to, ms, fn) => new Promise(res => {
      const from = scrollY, t0 = performance.now(), tok = anim = { id: 0 };
      const f = now => {
        if (anim !== tok) return res(false);
        const x = ms > 0 ? clamp((now - t0) / ms) : 1;
        scrollTo(0, from + (to - from) * (fn ? fn(x) : x));
        if (x < 1) tok.id = requestAnimationFrame(f); else res(true);
      };
      tok.id = requestAnimationFrame(f);
    });
    const jump = to => tween(to, Math.abs(to - scrollY) > 4 ? 600 : 0, ease);
    const through = async x => {                      /* run one chapter from wherever the page is, at a steady speed */
      if (scrollY < x.top - 4 && !(await jump(x.top))) return false;
      const d = x.end - scrollY;
      return d > 4 ? tween(x.end, d / innerHeight / (x.pin ? PIN : FLOW) * 1000) : true;
    };
    const playAll = async () => {
      playing = true; show();
      for (let i = cur(chs()); ; i++) {
        const c = chs(); if (i >= c.length) break;
        if (!(await through(c[i]))) return;
        if (i + 1 >= c.length || !(await tween(scrollY, c[i].pin ? 1100 : 300))) break;   /* hold on the finished stage */
        if (!(await jump(chs()[i + 1].top))) return;
      }
      stop();
    };
    const step = async dir => {
      stop();
      const c = chs(), i = cur(c);
      const k = dir > 0 ? i + 1 : (scrollY > c[i].top + 4 ? i : i - 1);
      if (k < 0 || k >= c.length) return;
      playing = dir > 0 && c[k].pin; show();
      if (!(await jump(c[k].top))) return;
      if (playing && !(await through(chs()[k]))) return;
      stop();
    };
    play.onclick = () => playing ? stop() : playAll();
    next.onclick = () => step(1);
    const mine = e => box.contains(e.target);
    addEventListener('wheel', stop, { passive: true });
    addEventListener('touchstart', e => { if (!mine(e)) stop(); }, { passive: true });
    addEventListener('pointerdown', e => { if (!mine(e)) stop(); });
    addEventListener('keydown', e => {
      if (/^(INPUT|TEXTAREA)$/.test(e.target.tagName) || e.metaKey || e.ctrlKey || e.altKey) return;
      if (e.key === 'ArrowRight') { e.preventDefault(); step(1); }
      else if (e.key === 'ArrowLeft') { e.preventDefault(); step(-1); }
      else if ([' ', 'PageDown', 'PageUp', 'ArrowDown', 'ArrowUp', 'Home', 'End', 'Escape'].includes(e.key) && !mine(e)) stop();
    });
    let q = false;
    addEventListener('scroll', () => { if (!q) { q = true; requestAnimationFrame(() => { q = false; show(); }); } }, { passive: true });
    addEventListener('resize', show); show();
  })();

  /* rows that cut in */
  const rev = $$('.reveal');
  if (still || !('IntersectionObserver' in window)) rev.forEach(r => r.classList.add('on'));
  else { const io = new IntersectionObserver(es => es.forEach(e => { if (e.isIntersecting) { e.target.classList.add('on'); io.unobserve(e.target); } }), { rootMargin: '0px 0px -12% 0px' }); rev.forEach(r => io.observe(r)); }

  /* generated photos replace the placeholders when the files exist */
  $$('.life img').forEach(i => { const ok = () => i.closest('figure').classList.add('has'); i.addEventListener('error', () => i.remove()); if (i.complete) { i.naturalWidth ? ok() : i.remove(); } else i.addEventListener('load', ok); });

  /* ---------- search demo ---------- */
  (function () {
    const ph = $('#demoPhone'); if (!ph || !D.labels) return;
    const labels = D.labels, stepsEl = $('#demoSteps'), stateEl = $('#demoState');
    const norm = s => s.toLowerCase();
    const sub = (q, s) => { let i = 0; for (const c of s) if (c === q[i]) i++; return i === q.length; };
    const score = (q, label) => {
      const s = norm(label), words = s.split(/\s+/);
      if (s === q) return 0; if (s.startsWith(q)) return 1;
      if (words.some(w => w.startsWith(q))) return 2;
      if (words.map(w => w[0]).join('').startsWith(q)) return 3;
      if (s.includes(q)) return 4; if (q.length > 2 && sub(q, s.replace(/\s/g, ''))) return 5;
      return -1;
    };
    const search = q => labels.map(l => [score(q, l), l]).filter(x => x[0] >= 0).sort((a, b) => a[0] - b[0] || a[1].localeCompare(b[1])).map(x => x[1]);
    let keys = 0, launched = false, auto = !still, timer;
    const render = (q, focus) => {
      const res = q ? search(norm(q)) : [];
      const show = res.slice(0, 4).reverse(), best = show.pop();
      ph.innerHTML = S.search({ rows: show.map(l => [l, 'App']), best: best || null, count: q ? `${res.length} result${res.length === 1 ? '' : 's'} · best match last` : 'Type to search 158 apps', input: `<input id="demoIn" type="text" inputmode="text" autocomplete="off" autocapitalize="off" spellcheck="false" aria-label="Search the demo app list" placeholder="Search apps and commands" value="${q.replace(/"/g, '')}">` });
      const input = $('#demoIn', ph);
      if (focus) { input.focus(); input.setSelectionRange(q.length, q.length); }
      input.oninput = () => { auto = false; clearTimeout(timer); keys++; step(input.value, true); };
      input.onkeydown = e => { if (e.key === 'Enter' && best) { keys++; launch(best); } };
      input.onfocus = () => { auto = false; clearTimeout(timer); };
      return res;
    };
    const status = (n, s, on) => { stepsEl.textContent = `${n} step${n === 1 ? '' : 's'}`; stateEl.textContent = s; stateEl.classList.toggle('on', !!on); };
    const launch = name => {
      launched = true; ph.innerHTML = S.app(name); status(1 + keys, 'launched', true);
      timer = setTimeout(() => { launched = false; keys = 0; render('', false); status(0, 'type something'); }, 2600);
    };
    const step = (q, focus) => {
      if (launched) return;
      const res = render(q, focus), plain = /^[a-z0-9 ]+$/i.test(q) && q.replace(/\s/g, '').length >= 2;
      if (plain && res.length === 1) return launch(res[0]);           /* unique match: launch while typing */
      status(q ? 1 + keys : 0, !q ? 'type something' : res.length ? `${res.length} match${res.length === 1 ? '' : 'es'} · Enter opens` : 'no match');
    };
    render('', false);
    const play = word => { if (!auto) return; keys = 0; let i = 0; const next = () => { if (!auto) return; i++; keys = i; step(word.slice(0, i), false); if (i < word.length && !launched) timer = setTimeout(next, 420); }; timer = setTimeout(next, 700); };
    if (auto && 'IntersectionObserver' in window) { const io = new IntersectionObserver(es => { if (es[0].isIntersecting) { io.disconnect(); play('vk'); } }, { threshold: .6 }); io.observe(ph); }
  })();

  /* this page's own numbers */
  addEventListener('load', () => setTimeout(() => {
    const out = $('#pagePerf'); if (!out || !performance.getEntriesByType) return;
    const nav = performance.getEntriesByType('navigation')[0]; if (!nav) return;
    const bytes = [nav, ...performance.getEntriesByType('resource')].reduce((a, e) => a + (e.transferSize || e.encodedBodySize || 0), 0);
    out.textContent = `This page: ${bytes ? Math.round(bytes / 1024) + ' KB, ' : ''}interactive in ${Math.round(nav.domInteractive)} ms on your machine.`;
  }, 0));
})();
